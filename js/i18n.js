const DICT = {};
I18N.forEach(([ru, en, tr]) => { DICT[ru] = LANG === 'tr' ? (tr || en) : en; });
function trText(s) {
  if (LANG === 'ru') return s;
  const k = s.trim();
  if (!k) return s;
  let r = DICT[k];
  if (r === undefined) {
    for (const [re, en, tr] of PATS) {
      const m = k.match(re);
      if (m) { r = ((LANG === 'tr' && tr) || en).replace(/\$(\d)/g, (_, i) => m[i]); break; }
    }
  }
  return r === undefined ? s : s.replace(k, r);
}
function translateNode(n) {
  if (n.nodeType === 3) { if (n.parentNode && /^(SCRIPT|STYLE)$/.test(n.parentNode.nodeName)) return; const v = trText(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; return; }
  if (n.nodeType !== 1 || /^(SCRIPT|STYLE|svg)$/i.test(n.nodeName)) return;
  if (n.title) n.title = trText(n.title);
  n.childNodes.forEach(translateNode);
}
